-- ── Step 2: Ensure all talukas exist in zones ──────────────────────────────────
-- Unique talukas from the XLS: BANKAPURA, BYADAGI, HANGAL, HAVERI, HIREKERUR,
-- HOOVINA HADAGALI, HUBLI, RANEBENNUR, RATTIHALLI, SAVANUR, SHIGGAON
-- slug = lowercase, spaces replaced with hyphens  e.g. "Hoovina Hadagali" → "hoovina-hadagali"
INSERT INTO zones (name, slug)
SELECT DISTINCT
  INITCAP(LOWER(x.taluk_name))                          AS name,
  LOWER(REPLACE(TRIM(x.taluk_name), ' ', '-'))           AS slug
FROM _xls_dealers x
WHERE x.taluk_name IS NOT NULL
  AND NOT EXISTS (
    SELECT 1 FROM zones z
    WHERE UPPER(z.name) = UPPER(x.taluk_name)
  );

-- ── Step 3a: Scrub conflicting phones from the temp table ─────────────────────
-- Null out any mobile that is ALREADY used by a different dealer in the DB.
-- This prevents unique constraint violations on dealers_phone_key regardless
-- of how many rows the UPDATE touches simultaneously.
UPDATE _xls_dealers x
SET mobile = NULL
WHERE x.mobile IS NOT NULL
  AND EXISTS (
    SELECT 1
    FROM   dealers d
    WHERE  d.phone       = x.mobile
      AND  d.deleted_at  IS NULL
      AND  UPPER(d.code) <> UPPER(x.code)   -- belongs to a DIFFERENT dealer
  );

-- Also null out phones that appear more than once inside the XLS itself
-- (two XLS rows cannot both claim the same number).
UPDATE _xls_dealers x
SET mobile = NULL
WHERE x.mobile IS NOT NULL
  AND (
    SELECT COUNT(*) FROM _xls_dealers x2 WHERE x2.mobile = x.mobile
  ) > 1;

-- Report what was skipped
DO $$
DECLARE r RECORD; any_skipped BOOLEAN := false;
BEGIN
  FOR r IN
    SELECT x.code, d.phone AS old_phone, d2.code AS taken_by
    FROM   _xls_dealers x
    JOIN   dealers d  ON UPPER(d.code) = UPPER(x.code) AND d.deleted_at IS NULL
    JOIN   dealers d2 ON d2.phone = d.phone              -- same number on another dealer
                     AND d2.id   <> d.id
                     AND d2.deleted_at IS NULL
    WHERE  x.mobile IS NULL                              -- these were just nulled out
  LOOP
    any_skipped := true;
    RAISE NOTICE '⚠️  Phone skipped for code % — number % already assigned to code %',
      r.code, r.old_phone, r.taken_by;
  END LOOP;
  IF NOT any_skipped THEN
    RAISE NOTICE '✅ No phone conflicts — all numbers will be updated';
  END IF;
END $$;

-- ── Step 3b: Update matched dealers ───────────────────────────────────────────
-- Never touches route_id or location_label.
-- mobile is already NULL for any conflicting rows, so COALESCE keeps old phone.
UPDATE dealers d
SET
  phone         = COALESCE(x.mobile, d.phone),
  pin_code      = COALESCE(x.pin_code, d.pin_code),
  zone_id       = COALESCE(
                    (SELECT z.id FROM zones z WHERE UPPER(z.name) = UPPER(x.taluk_name) LIMIT 1),
                    d.zone_id
                  ),
  rate_category = COALESCE(x.rate_category, d.rate_category),
  customer_type = COALESCE(x.customer_type::customer_type, d.customer_type),
  active        = true,
  updated_at    = NOW()
FROM _xls_dealers x
WHERE UPPER(d.code) = UPPER(x.code)
  AND d.deleted_at  IS NULL;

